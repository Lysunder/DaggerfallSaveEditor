// Generates src/data/itemTemplates.ts from the Daggerfall Unity source.
// Usage: node scripts/generate-item-data.mjs <path to daggerfall-unity>
// Reads Assets/Resources/ItemTemplates.txt and Assets/Scripts/Game/Items/ItemEnums.cs.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const dfu = process.argv[2];
if (!dfu) {
  console.error('Usage: node scripts/generate-item-data.mjs <path to daggerfall-unity>');
  process.exit(1);
}

const read = (path) => readFileSync(join(dfu, path), 'utf-8').replace(/^﻿/, '');

const templates = JSON.parse(read('Assets/Resources/ItemTemplates.txt'));
templates.forEach((template, position) => {
  if (template.index !== position) throw new Error(`Template ${template.name} is at ${position} but has index ${template.index}`);
});

// Every `public enum Name { A = 1, B, ... }` in ItemEnums.cs, in declaration order.
// Values without an initializer follow the previous value, as in C#.
const enumSource = read('Assets/Scripts/Game/Items/ItemEnums.cs')
  .replace(/\/\/.*$/gm, '')
  .replace(/\/\*[\s\S]*?\*\//g, '');
const enums = {};
for (const match of enumSource.matchAll(/public enum (\w+)\s*\{([^}]*)\}/g)) {
  const [, name, body] = match;
  let next = 0;
  enums[name] = body.split(',').map((entry) => entry.trim()).filter(Boolean).map((entry) => {
    const [member, value] = entry.split('=').map((part) => part.trim());
    const number = value === undefined ? next : Number(value);
    if (!Number.isInteger(number)) throw new Error(`Can't read ${name}.${member} = ${value}`);
    next = number + 1;
    return [member, number];
  });
}

const groups = Object.fromEntries(enums.ItemGroups.filter(([, value]) => value >= 0));

// Each group's enum lists template indices; an item's groupIndex is its position in that list.
// Groups whose enum doesn't hold template indices (artifacts, magic items, deeds) are left out.
const notTemplateIndices = new Set(['MagicItems', 'Artifacts', 'Deeds']);
const groupTemplates = {};
for (const group of Object.keys(groups)) {
  if (notTemplateIndices.has(group)) continue;
  const members = enums[group];
  if (!members) throw new Error(`No enum for item group ${group}`);
  groupTemplates[group] = members.map(([member, index]) => {
    if (!templates[index]) throw new Error(`${group}.${member} = ${index} is not a template`);
    return index;
  });
}

const materials = (name) => Object.fromEntries(enums[name].filter(([, value]) => value >= 0));

let commit = 'unknown';
try {
  commit = execFileSync('git', ['-C', dfu, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf-8' }).trim();
} catch { /* not a git checkout */ }

const fields = [
  'index', 'name', 'baseWeight', 'hitPoints', 'basePrice', 'enchantmentPoints', 'variants', 'drawOrderOrEffect',
  'isIngredient', 'worldTextureArchive', 'worldTextureRecord', 'playerTextureArchive', 'playerTextureRecord',
];
const templateLines = templates.map((template) => `  [${fields.map((field) => JSON.stringify(template[field])).join(', ')}],`);

const output = `// Generated by scripts/generate-item-data.mjs from Daggerfall Unity ${commit}. Do not edit by hand.
// Sources: Assets/Resources/ItemTemplates.txt and Assets/Scripts/Game/Items/ItemEnums.cs.

export interface ItemTemplate {
${fields.map((field) => `  ${field}: ${field === 'name' ? 'string' : field === 'isIngredient' ? 'boolean' : 'number'};`).join('\n')}
}

const TEMPLATE_ROWS: [${fields.map((field) => (field === 'name' ? 'string' : field === 'isIngredient' ? 'boolean' : 'number')).join(', ')}][] = [
${templateLines.join('\n')}
];

/** All ${templates.length} classic item templates, by template index. */
export const ITEM_TEMPLATES: ItemTemplate[] = TEMPLATE_ROWS.map(
  ([${fields.join(', ')}]) => ({ ${fields.join(', ')} }),
);

/** ItemGroups enum: group name → value. */
export const ITEM_GROUPS = ${JSON.stringify(groups, null, 2)} as const;

export type ItemGroupName = keyof typeof ITEM_GROUPS;

/** Template indices of each group, in enum order. An item's groupIndex is the position in its group's list. */
export const GROUP_TEMPLATES: Partial<Record<ItemGroupName, number[]>> = ${JSON.stringify(groupTemplates)};

/** WeaponMaterialTypes enum: name → value. */
export const WEAPON_MATERIALS = ${JSON.stringify(materials('WeaponMaterialTypes'), null, 2)} as const;

/** ArmorMaterialTypes enum: name → value. */
export const ARMOR_MATERIALS = ${JSON.stringify(materials('ArmorMaterialTypes'), null, 2)} as const;
`;

const target = new URL('../src/data/itemTemplates.ts', import.meta.url);
writeFileSync(target, output);
console.log(`Wrote ${templates.length} templates and ${Object.keys(groupTemplates).length} groups to src/data/itemTemplates.ts`);
